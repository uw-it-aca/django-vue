import json
import re
from pathlib import Path

from django.conf import settings

# Module-level cache: stores (mtime, routes, compiled_patterns)
_cache = {"mtime": None, "routes": None, "compiled": None}


def _get_manifest_path():
    """Resolve the path to the Vue route manifest.

    In localdev, the development path (under BASE_DIR) is checked first
    so that freshly-built manifests from the node-bundler volume mount
    take priority over the stale copy in STATIC_ROOT (baked at image build).
    In production, STATIC_ROOT is the only location that exists.
    """
    candidates = []

    # Development path — written by vite build (--watch) into the app's
    # static directory, shared via Docker volume mount in localdev.
    candidates.append(
        Path(settings.BASE_DIR)
        / "app_name"
        / "static"
        / "app_name"
        / "vue-routes.json"
    )

    # Production path — populated by collectstatic at image build time.
    static_root = getattr(settings, "STATIC_ROOT", None)
    if static_root:
        candidates.append(Path(static_root) / "app_name" / "vue-routes.json")

    for manifest_path in candidates:
        if manifest_path.exists():
            return manifest_path

    return None


def _route_to_regex(route):
    """
    Convert a Vue route pattern to a compiled regex.

    Examples:
        /home           → ^/home$
        /users/:id      → ^/users/[^/]+$
        /posts/:id/edit → ^/posts/[^/]+/edit$
    """
    pattern = re.sub(r":(\w+)", r"[^/]+", route)
    return re.compile(f"^{pattern}$")


def _load_manifest():
    """
    Load the Vue route manifest, using mtime to detect changes.

    In production the file never changes (read once). In dev mode,
    the file updates on each Vite rebuild and Django picks it up
    on the next request without a restart.
    """
    manifest_path = _get_manifest_path()
    if manifest_path is None:
        return None, None

    mtime = manifest_path.stat().st_mtime

    if mtime == _cache["mtime"]:
        return _cache["routes"], _cache["compiled"]

    with open(manifest_path) as f:
        routes = json.load(f).get("routes", [])

    compiled = [_route_to_regex(route) for route in routes]

    _cache["mtime"] = mtime
    _cache["routes"] = routes
    _cache["compiled"] = compiled

    return routes, compiled


def get_vue_routes():
    """
    Load the Vue route manifest generated by vite-plugin-vue-route-manifest.

    Returns a list of route pattern strings, or None if the manifest
    is not available (e.g., during local dev before a build).
    """
    routes, _ = _load_manifest()
    return routes


def is_valid_vue_route(path):
    """
    Check if a URL path matches a known Vue route from the manifest.

    Returns True if:
    - The path matches a route in the manifest, OR
    - No manifest is available (fail open for dev mode)
    """
    _, compiled = _load_manifest()
    if compiled is None:
        return True  # No manifest available — fail open

    # Normalize: ensure leading slash, strip trailing slash (except root)
    normalized = "/" + path.strip("/") if path.strip("/") else "/"

    for pattern in compiled:
        if pattern.match(normalized):
            return True

    return False
